"""
UMAP dimensional reduction visualizations using plotnine.
Requires: src/final_figures/output/umap_coords_metadata.csv
          (generated by 00_extract_h5ad_data.py)

Outputs (src/final_figures/output/figures/):
  umap_overview.pdf       – 2×2 panel: cluster / age / condition / area
  umap_by_condition.pdf   – faceted by age × condition, colored by cluster
"""

import os
import sys
import warnings

import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
from matplotlib.backends.backend_pdf import PdfPages
import matplotlib.pyplot as plt
from plotnine import (
    ggplot, aes, geom_point, facet_wrap, scale_color_manual,
    scale_color_discrete, labs, theme_void, theme, element_text,
    element_blank, element_rect, guides, guide_legend,
    coord_fixed,
)
from plotnine.scales import scale_color_brewer
import itertools

warnings.filterwarnings("ignore")

BASE    = "/dfs9/ucightf-lab/projects/ChatS/251006_0925Bio-06_ChatS_xenium"
DATADIR = os.path.join(BASE, "src/final_figures/output")
OUTDIR  = os.path.join(BASE, "src/final_figures/output/figures")
os.makedirs(OUTDIR, exist_ok=True)

umap_file = os.path.join(DATADIR, "umap_coords_metadata.csv")
if not os.path.exists(umap_file):
    sys.exit(f"Run 00_extract_h5ad_data.py first – missing:\n  {umap_file}")

cells = pd.read_csv(umap_file)
cells["leiden_harmony"] = cells["leiden_harmony"].astype(str)

# ── Color palettes ─────────────────────────────────────────────────────────────
_paired  = ["#A6CEE3","#1F78B4","#B2DF8A","#33A02C","#FB9A99","#E31A1C",
            "#FDBF6F","#FF7F00","#CAB2D6","#6A3D9A","#FFFF99","#B15928"]
_set2    = ["#66C2A5","#FC8D62","#8DA0CB","#E78AC3","#A6D854","#FFD92F"]
_all_cols = _paired + _set2
n_clust  = cells["leiden_harmony"].nunique()
clust_ids = sorted(cells["leiden_harmony"].unique(), key=lambda x: int(x))
clust_pal = {c: _all_cols[i % len(_all_cols)] for i, c in enumerate(clust_ids)}

age_pal  = {"adult": "#2166AC", "aged": "#D73027"}
cond_pal = {"control": "#66C2A5", "heatstress": "#FC8D62"}
area_pal = {"area_1": "#7B2D8B", "area_2": "#E6932A",
            "area_3": "#2E8B57", "area_4": "#C0392B"}

PT_SIZE  = 0.12
PT_ALPHA = 0.35

THEME_UMAP = (
    theme_void(base_size=9) +
    theme(
        legend_title     = element_text(size=8, face="bold"),
        legend_text      = element_text(size=7),
        legend_key_size  = 6,
        plot_title       = element_text(size=10, face="bold", ha="center"),
        plot_margin      = 0.02,
    )
)


def umap_panel(df, color_col, palette, title, legend_ncol=1,
               legend_point_size=2.0):
    """Return a single plotnine UMAP ggplot object."""
    df = df.sample(frac=1, random_state=42).copy()   # shuffle for layering
    df[color_col] = df[color_col].astype(str)

    p = (
        ggplot(df, aes("UMAP1", "UMAP2", color=color_col))
        + geom_point(size=PT_SIZE, alpha=PT_ALPHA)
        + scale_color_manual(values=palette, name=color_col.replace("_", " ").title())
        + guides(color=guide_legend(
            override_aes={"size": legend_point_size, "alpha": 1.0},
            ncol=legend_ncol,
        ))
        + labs(title=title)
        + THEME_UMAP
    )
    return p


# ── Draw one plotnine figure to a matplotlib Axes ─────────────────────────────
def draw_to_ax(p, ax):
    """Render a plotnine plot into an existing matplotlib Axes."""
    fig = p.draw()
    fig.set_size_inches(5, 4)
    ax.set_axis_off()
    # Copy rendered figure as image into the axes
    fig.canvas.draw()
    buf = fig.canvas.buffer_rgba()
    import numpy as np
    img = np.frombuffer(buf, dtype=np.uint8).reshape(
        fig.canvas.get_width_height()[::-1] + (4,)
    )
    ax.imshow(img)
    plt.close(fig)


# ── Overview: 2×2 grid ────────────────────────────────────────────────────────
print("Building UMAP overview...")

p_cluster = umap_panel(cells, "leiden_harmony", clust_pal,
                        "Leiden Clusters", legend_ncol=2)
p_age     = umap_panel(cells, "age",  age_pal,  "Age")
p_cond    = umap_panel(cells, "condition", cond_pal, "Condition")

if "area" in cells.columns:
    p_area = umap_panel(cells, "area", area_pal, "Brain Area")
else:
    p_area = None

# Save panels individually then assemble with matplotlib
panel_files = []
for label, p in [("cluster", p_cluster), ("age", p_age),
                  ("cond", p_cond), ("area", p_area)]:
    if p is None:
        panel_files.append(None)
        continue
    tmp = os.path.join(OUTDIR, f"_tmp_umap_{label}.png")
    p.save(tmp, width=5, height=4, dpi=150, verbose=False)
    panel_files.append(tmp)

fig_overview, axes = plt.subplots(2, 2, figsize=(14, 11))
titles = ["Leiden Clusters", "Age", "Condition", "Brain Area"]
for ax, tmp, ttl in zip(axes.flat, panel_files, titles):
    ax.set_axis_off()
    if tmp and os.path.exists(tmp):
        img = plt.imread(tmp)
        ax.imshow(img)
    ax.set_title(ttl, fontsize=11, fontweight="bold", pad=4)

fig_overview.suptitle("UMAP – Harmony-integrated Xenium data",
                       fontsize=14, fontweight="bold", y=1.01)
fig_overview.tight_layout()
fig_overview.savefig(os.path.join(OUTDIR, "umap_overview.pdf"),
                     bbox_inches="tight", dpi=150)
plt.close(fig_overview)

# Clean up temp files
for tmp in panel_files:
    if tmp and os.path.exists(tmp):
        os.remove(tmp)

print("  Saved: umap_overview.pdf")

# ── Faceted UMAP: age × condition ─────────────────────────────────────────────
print("Building faceted UMAP...")

cells["facet_label"] = (
    cells["age"].str.capitalize() + "\n" + cells["condition"].str.capitalize()
)
facet_order = ["Adult\nControl", "Adult\nHeatstress",
               "Aged\nControl",  "Aged\nHeatstress"]
present = [f for f in facet_order if f in cells["facet_label"].unique()]
cells["facet_label"] = pd.Categorical(cells["facet_label"],
                                       categories=present, ordered=True)

df_shuf = cells.sample(frac=1, random_state=42)

p_facet = (
    ggplot(df_shuf, aes("UMAP1", "UMAP2", color="leiden_harmony"))
    + geom_point(size=0.1, alpha=0.3)
    + facet_wrap("facet_label", nrow=2)
    + scale_color_manual(values=clust_pal, name="Cluster")
    + guides(color=guide_legend(
        override_aes={"size": 2.5, "alpha": 1.0},
        ncol=3,
    ))
    + labs(title="UMAP by Age × Condition")
    + THEME_UMAP
    + theme(
        strip_background = element_rect(fill="#2C3E50", color="#2C3E50"),
        strip_text       = element_text(color="white", size=9),
        panel_spacing    = 0.02,
    )
)

p_facet.save(os.path.join(OUTDIR, "umap_by_condition.pdf"),
             width=14, height=9, dpi=150, verbose=False)
print("  Saved: umap_by_condition.pdf")

print("\nDone.")
